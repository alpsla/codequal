/**
 * Execute cloud fixers and merge results with CLI fixer results
 *
 * This is the main integration point with the 3-tier fix flow.
 * Call this after Tier 2 (dedicated fixers) and before Tier 3 (AI-only).
 */
export async function executeCloudFixers(
  issues: Issue[],
  options: {
    tier: SubscriptionTier;
    language: string;
    sourceCode?: Map<string, string>;
    repositoryUrl?: string;
    branch?: string;
    existingFixes?: GeneratedFix[]; // Fixes from Tier 1/2
  }
): Promise<{
  fixes: GeneratedFix[];
  cloudResult: CloudAPIResult;
}> {
  const orchestrator = getCloudAPIOrchestrator();

  // Filter out issues that already have fixes from Tier 1/2
  const existingFixIds = new Set(options.existingFixes?.map(f => f.issueId) || []);
  const unfixedIssues = issues.filter(issue => {
    const issueId = `${issue.rule}-${issue.file}-${issue.line}`;
    return !existingFixIds.has(issueId);
  });

  // Execute cloud fixers on unfixed issues
  const cloudResult = await orchestrator.execute({
    tier: options.tier,
    issues: unfixedIssues,
    sourceCode: options.sourceCode,
    language: options.language,
    repositoryUrl: options.repositoryUrl,
    branch: options.branch
  });

  // Merge fixes (Tier 1/2 + Cloud API)
  const allFixes = [
    ...(options.existingFixes || []),
    ...cloudResult.fixes
  ];

  return {
    fixes: allFixes,
    cloudResult
  };
}

/**
 * Check if cloud fixers can provide value for the given issues
 */
export function canCloudFixersHelp(
  issues: Issue[],
  tier: SubscriptionTier
): { canHelp: boolean; reason: string; potentialFixes: number } {
  const orchestrator = getCloudAPIOrchestrator();

  if (!orchestrator.isAvailable(tier)) {
    return {
      canHelp: false,
      reason: tier === 'basic'
        ? 'Upgrade to PRO for AI-powered fixes'
        : 'Cloud fixers not configured',
      potentialFixes: 0
    };
  }

  // Count issues that could benefit from cloud fixes
  // (security issues, complex bugs, etc.)
  const cloudFixableCategories = ['security', 'bugs', 'vulnerability'];
  const potentialFixes = issues.filter(issue =>
    cloudFixableCategories.includes(issue.category?.toLowerCase() || '')
  ).length;

  if (potentialFixes === 0) {
    return {
      canHelp: false,
      reason: 'No issues suitable for AI-powered fixes',
      potentialFixes: 0
    };
  }

  return {
    canHelp: true,
    reason: `${potentialFixes} issues can be fixed by Corgea AI`,
    potentialFixes
  };
}
