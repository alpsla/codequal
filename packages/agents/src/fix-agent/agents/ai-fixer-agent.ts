/**
 * AI-Fixer Agent
 *
 * Handles Tier 2 issues (<60% confidence) by:
 * 1. Using tool context (suggestions, patterns) as prep work
 * 2. Generating fix recommendations using AI
 * 3. Enriching issues with AI-generated fixes
 *
 * This agent serves as the bridge between tool validators and role agents.
 * For issues where tool fixers can't auto-fix with high confidence,
 * this agent uses AI to generate fix recommendations.
 *
 * Architecture:
 * - Receives issues from SupabaseFixRouter with <60% confidence
 * - Queries Supabase for AI model configuration (no hardcoded models)
 * - Uses tool context to guide AI fix generation
 * - Outputs enriched issues ready for Role Agents
 */

import { createClient, SupabaseClient } from '@supabase/supabase-js';
import OpenAI from 'openai';
import {
  getFixPatternRegistry,
  createAIFixerVerifier,
  AIFixerVerifier,
} from '../fix-pattern-registry';

// ============================================================================
// TYPES
// ============================================================================

/**
 * Issue to be processed by AI-Fixer
 * Includes tool context as "prep work" for AI
 */
export interface AIFixerIssue {
  id: string;
  validatorToolId: string;
  ruleId: string;
  file: string;
  line: number;
  column?: number;
  message: string;
  severity: 'critical' | 'high' | 'medium' | 'low';
  codeContext?: string;
  language: string;

  // Tool context (prep work from validator)
  toolContext?: {
    toolSuggestion?: string;
    ruleDescription?: string;
    recommendedPattern?: string;
    relatedRules?: string[];
    bestPractices?: string;
  };

  // Original confidence from tool (must be <60% to be here)
  originalConfidence: number;
}

/**
 * Fix recommendation generated by AI-Fixer
 */
export interface AIFixRecommendation {
  fix: string;
  correctedCode: string;
  explanation: string;
  issueDescription?: {
    what: string;
    why: string;
    causes: string[];
    impact: string;
  };
  bestPractices: string[];
  confidence: number;
  model: string;
  cost?: number;
  usage?: {
    promptTokens: number;
    completionTokens: number;
    totalTokens: number;
  };
}

/**
 * Enriched issue ready for Role Agents
 */
export interface EnrichedIssue extends AIFixerIssue {
  tier: 2;
  fixRecommendation: AIFixRecommendation;
  aiProcessedAt: Date;
}

/**
 * Batch result from AI-Fixer
 */
export interface AIFixerBatchResult {
  enrichedIssues: EnrichedIssue[];
  failed: {
    issue: AIFixerIssue;
    error: string;
  }[];
  summary: {
    total: number;
    processed: number;
    failed: number;
    totalCost: number;
    avgConfidence: number;
    processingTimeMs: number;
  };
}

// ============================================================================
// AI-FIXER AGENT
// ============================================================================

export class AIFixerAgent {
  private supabase: SupabaseClient;
  private openRouter: OpenAI;
  private modelCache: Map<string, string> = new Map();
  private fixerVerifier: AIFixerVerifier | null = null;
  private submitToRegistry = false;

  constructor(options?: { submitToRegistry?: boolean }) {
    this.submitToRegistry = options?.submitToRegistry ?? false;
    if (!process.env.SUPABASE_URL || !process.env.SUPABASE_SERVICE_ROLE_KEY) {
      throw new Error('SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY must be set');
    }

    this.supabase = createClient(
      process.env.SUPABASE_URL,
      process.env.SUPABASE_SERVICE_ROLE_KEY
    );

    const openRouterConfig: any = {
      apiKey: process.env.OPENROUTER_API_KEY || '',
    };

    if (process.env.OPENROUTER_API_KEY?.startsWith('sk-or-')) {
      openRouterConfig.baseURL = 'https://openrouter.ai/api/v1';
      openRouterConfig.defaultHeaders = {
        'HTTP-Referer': 'https://codequal.com',
        'X-Title': 'CodeQual AI-Fixer Agent',
      };
    }

    this.openRouter = new OpenAI(openRouterConfig);
  }

  // ==========================================================================
  // MAIN PROCESSING
  // ==========================================================================

  /**
   * Process a single issue and generate AI fix recommendation
   */
  async processIssue(issue: AIFixerIssue): Promise<EnrichedIssue> {
    const startTime = Date.now();

    // Get AI model for this language
    const model = await this.getModelForLanguage(issue.language);

    // Generate fix using AI with tool context
    const recommendation = await this.generateFixRecommendation(issue, model);

    return {
      ...issue,
      tier: 2,
      fixRecommendation: recommendation,
      aiProcessedAt: new Date(),
    };
  }

  /**
   * Process a batch of issues in parallel
   */
  async processBatch(
    issues: AIFixerIssue[],
    options: { parallel?: number; verbose?: boolean } = {}
  ): Promise<AIFixerBatchResult> {
    const startTime = Date.now();
    const parallel = options.parallel || 3;
    const enrichedIssues: EnrichedIssue[] = [];
    const failed: { issue: AIFixerIssue; error: string }[] = [];
    let totalCost = 0;

    // Process in batches
    for (let i = 0; i < issues.length; i += parallel) {
      const batch = issues.slice(i, i + parallel);

      const results = await Promise.allSettled(
        batch.map((issue) => this.processIssue(issue))
      );

      for (let j = 0; j < results.length; j++) {
        const result = results[j];
        const issue = batch[j];

        if (result.status === 'fulfilled') {
          enrichedIssues.push(result.value);
          totalCost += result.value.fixRecommendation.cost || 0;

          if (options.verbose) {
            console.log(
              `[AI-Fixer] Processed ${issue.file}:${issue.line} - ` +
                `${issue.ruleId} (${result.value.fixRecommendation.confidence}%)`
            );
          }
        } else {
          failed.push({
            issue,
            error: result.reason?.message || 'Unknown error',
          });

          if (options.verbose) {
            console.log(
              `[AI-Fixer] Failed ${issue.file}:${issue.line} - ${result.reason?.message}`
            );
          }
        }
      }
    }

    // Calculate average confidence
    const avgConfidence =
      enrichedIssues.length > 0
        ? enrichedIssues.reduce(
            (sum, i) => sum + i.fixRecommendation.confidence,
            0
          ) / enrichedIssues.length
        : 0;

    return {
      enrichedIssues,
      failed,
      summary: {
        total: issues.length,
        processed: enrichedIssues.length,
        failed: failed.length,
        totalCost,
        avgConfidence: Math.round(avgConfidence),
        processingTimeMs: Date.now() - startTime,
      },
    };
  }

  // ==========================================================================
  // AI FIX GENERATION
  // ==========================================================================

  /**
   * Generate fix recommendation using AI with tool context
   */
  private async generateFixRecommendation(
    issue: AIFixerIssue,
    model: string
  ): Promise<AIFixRecommendation> {
    const systemPrompt = this.buildSystemPrompt(issue);
    const userPrompt = this.buildUserPrompt(issue);

    try {
      const response = await this.openRouter.chat.completions.create({
        model,
        messages: [
          { role: 'system', content: systemPrompt },
          { role: 'user', content: userPrompt },
        ],
        temperature: 0.3,
        max_tokens: 2500,
      });

      const content = response.choices[0]?.message?.content || '';
      const parsed = this.parseAIResponse(content, issue);

      // Calculate usage
      const usage = {
        promptTokens: response.usage?.prompt_tokens || 0,
        completionTokens: response.usage?.completion_tokens || 0,
        totalTokens: response.usage?.total_tokens || 0,
      };

      // Estimate cost (varies by model)
      const cost = this.estimateCost(model, usage);

      return {
        ...parsed,
        confidence: this.calculateConfidence(parsed, issue),
        model,
        cost,
        usage,
      };
    } catch (error: any) {
      console.error(`[AI-Fixer] Error generating fix:`, error.message);

      // Return fallback recommendation
      return {
        fix: `Address ${issue.severity} ${issue.ruleId} issue`,
        correctedCode: issue.codeContext || '// Fix required',
        explanation: `AI could not generate fix: ${error.message}`,
        bestPractices: [],
        confidence: 30,
        model,
      };
    }
  }

  /**
   * Build system prompt for AI
   */
  private buildSystemPrompt(issue: AIFixerIssue): string {
    return `You are an expert code fixer. Generate precise, compilable fixes for code issues.

CONTEXT:
- Language: ${issue.language}
- Validator Tool: ${issue.validatorToolId}
- Rule: ${issue.ruleId}
- Severity: ${issue.severity}

${
  issue.toolContext?.toolSuggestion
    ? `TOOL SUGGESTION (use as guidance):
${issue.toolContext.toolSuggestion}`
    : ''
}

${
  issue.toolContext?.recommendedPattern
    ? `RECOMMENDED PATTERN:
${issue.toolContext.recommendedPattern}`
    : ''
}

${
  issue.toolContext?.bestPractices
    ? `BEST PRACTICES:
${issue.toolContext.bestPractices}`
    : ''
}

OUTPUT FORMAT (JSON only, no explanation outside JSON):
{
  "fix": "Step-by-step description of the fix",
  "correctedCode": "The corrected code that replaces the problematic code",
  "explanation": "Brief explanation of why this fix works",
  "issueDescription": {
    "what": "What is this issue (2-3 sentences, rule-specific)",
    "why": "Why it matters (2-3 sentences with consequences)",
    "causes": ["Cause 1", "Cause 2", "Cause 3"],
    "impact": "Impact if not fixed (2-3 sentences)"
  },
  "bestPractices": ["Best practice 1", "Best practice 2", "Best practice 3"]
}

CRITICAL: Output ONLY valid JSON. No markdown, no explanation text.`;
  }

  /**
   * Build user prompt with issue details
   */
  private buildUserPrompt(issue: AIFixerIssue): string {
    return `Fix this ${issue.severity} issue:

FILE: ${issue.file}
LINE: ${issue.line}
RULE: ${issue.ruleId}
MESSAGE: ${issue.message}

${
  issue.codeContext
    ? `CODE CONTEXT:
\`\`\`${issue.language}
${issue.codeContext}
\`\`\``
    : 'No code context available - generate fix based on rule and message.'
}

Provide the fix as JSON.`;
  }

  /**
   * Parse AI response into structured recommendation
   */
  private parseAIResponse(
    content: string,
    issue: AIFixerIssue
  ): Omit<AIFixRecommendation, 'confidence' | 'model' | 'cost' | 'usage'> {
    // Clean response
    let cleaned = content.trim();

    // Remove markdown code blocks
    cleaned = cleaned.replace(/```json\s*/gi, '');
    cleaned = cleaned.replace(/```\s*/gi, '');

    // Try to parse JSON
    try {
      // Find JSON object
      const jsonMatch = cleaned.match(/\{[\s\S]*\}/);
      if (jsonMatch) {
        const parsed = JSON.parse(jsonMatch[0]);

        return {
          fix: parsed.fix || 'Fix not generated',
          correctedCode: parsed.correctedCode || issue.codeContext || '',
          explanation: parsed.explanation || parsed.fix || '',
          issueDescription: parsed.issueDescription,
          bestPractices: parsed.bestPractices || [],
        };
      }
    } catch (e) {
      // JSON parsing failed
    }

    // Fallback: extract what we can from text
    return {
      fix: cleaned.length > 500 ? cleaned.substring(0, 500) : cleaned,
      correctedCode: issue.codeContext || '// Fix required',
      explanation: 'AI response could not be parsed as JSON',
      bestPractices: [],
    };
  }

  /**
   * Calculate confidence based on AI response quality
   */
  private calculateConfidence(
    recommendation: Omit<
      AIFixRecommendation,
      'confidence' | 'model' | 'cost' | 'usage'
    >,
    issue: AIFixerIssue
  ): number {
    let confidence = 60; // Base confidence for AI fix

    // Boost if we have corrected code
    if (
      recommendation.correctedCode &&
      recommendation.correctedCode !== issue.codeContext
    ) {
      confidence += 10;
    }

    // Boost if we have structured issue description
    if (recommendation.issueDescription?.what) {
      confidence += 5;
    }

    // Boost if we have best practices
    if (recommendation.bestPractices.length > 0) {
      confidence += 5;
    }

    // Boost if tool provided suggestions (used as context)
    if (issue.toolContext?.toolSuggestion) {
      confidence += 10;
    }

    // Cap at 90% (only tool fixers should hit 95%+)
    return Math.min(90, confidence);
  }

  // ==========================================================================
  // MODEL CONFIGURATION
  // ==========================================================================

  /**
   * Get AI model for language from Supabase
   * Models are configured via quarterly research, not hardcoded
   */
  private async getModelForLanguage(language: string): Promise<string> {
    // Check cache
    if (this.modelCache.has(language)) {
      return this.modelCache.get(language)!;
    }

    try {
      const { data, error } = await this.supabase
        .from('model_configurations')
        .select('primary_model')
        .eq('role', 'ai_fixer')
        .eq('language', language)
        .single();

      if (!error && data?.primary_model) {
        this.modelCache.set(language, data.primary_model);
        return data.primary_model;
      }
    } catch (e) {
      // Query failed
    }

    // Fallback to generic model if no language-specific config
    const fallback = 'google/gemini-2.0-flash-001';
    console.warn(
      `[AI-Fixer] No model config for ${language}, using fallback: ${fallback}`
    );
    return fallback;
  }

  /**
   * Estimate cost based on model and usage
   */
  private estimateCost(
    model: string,
    usage: { promptTokens: number; completionTokens: number }
  ): number {
    // Approximate costs per 1K tokens (2025 pricing)
    const pricing: Record<string, { input: number; output: number }> = {
      'google/gemini-2.0-flash-001': { input: 0.00015, output: 0.0006 },
      'anthropic/claude-sonnet-4-20250514': { input: 0.003, output: 0.015 },
      'openai/gpt-4o': { input: 0.005, output: 0.015 },
      'deepseek/deepseek-coder': { input: 0.00014, output: 0.00028 },
    };

    const modelPricing = pricing[model] || { input: 0.001, output: 0.002 };

    return (
      (usage.promptTokens / 1000) * modelPricing.input +
      (usage.completionTokens / 1000) * modelPricing.output
    );
  }

  // ==========================================================================
  // UTILITY METHODS
  // ==========================================================================

  /**
   * Clear model cache (call after configuration updates)
   */
  clearModelCache(): void {
    this.modelCache.clear();
  }

  /**
   * Get processing summary
   */
  getStats(): { modelCache: number } {
    return {
      modelCache: this.modelCache.size,
    };
  }

  // ==========================================================================
  // PATTERN REGISTRY INTEGRATION
  // ==========================================================================

  /**
   * Enable submission to pattern registry
   * When enabled, successful AI fixes are verified and submitted to the registry
   */
  enableRegistrySubmission(): void {
    this.submitToRegistry = true;
    if (!this.fixerVerifier) {
      this.fixerVerifier = createAIFixerVerifier({
        maxAttempts: 2,
        minScore: 80,
        dryRun: false,
      });
    }
  }

  /**
   * Disable submission to pattern registry
   */
  disableRegistrySubmission(): void {
    this.submitToRegistry = false;
  }

  /**
   * Submit a generated fix to the pattern registry
   * The fix goes through verification and then the approval workflow
   */
  async submitFixToRegistry(
    issue: AIFixerIssue,
    recommendation: AIFixRecommendation
  ): Promise<{ submitted: boolean; patternStatus?: string; message?: string }> {
    if (!this.submitToRegistry) {
      return { submitted: false, message: 'Registry submission disabled' };
    }

    if (!this.fixerVerifier) {
      this.fixerVerifier = createAIFixerVerifier({
        maxAttempts: 2,
        minScore: 80,
        dryRun: false,
      });
    }

    try {
      const result = await this.fixerVerifier.verifyAndSubmit({
        ruleId: issue.ruleId,
        tool: issue.validatorToolId,
        filePath: issue.file,
        originalCode: issue.codeContext || '',
        fixedCode: recommendation.correctedCode,
        lineNumber: issue.line,
        issueMessage: issue.message,
        aiModel: recommendation.model,
        attemptNumber: 1,
      });

      if (result.success && result.patternResponse) {
        console.log(
          `[AI-Fixer] Fix submitted to registry: ${result.patternResponse.status}`
        );
        return {
          submitted: true,
          patternStatus: result.patternResponse.status,
          message: result.patternResponse.message,
        };
      }

      return {
        submitted: false,
        message: result.failureReason || 'Verification failed',
      };
    } catch (error: any) {
      console.error(`[AI-Fixer] Registry submission error:`, error.message);
      return { submitted: false, message: error.message };
    }
  }

  /**
   * Get AI Fixer's current trust status in the registry
   */
  getAIFixerTrustStatus(): {
    totalPatterns: number;
    activePatterns: number;
    pendingPatterns: number;
  } {
    const registry = getFixPatternRegistry();
    return registry.getAIFixerStats();
  }
}

// ============================================================================
// SINGLETON EXPORT
// ============================================================================

let instance: AIFixerAgent | null = null;

export function getAIFixerAgent(options?: { submitToRegistry?: boolean }): AIFixerAgent {
  if (!instance) {
    instance = new AIFixerAgent(options);
  }
  return instance;
}

/**
 * Reset the AI Fixer Agent singleton (for testing)
 */
export function resetAIFixerAgent(): void {
  instance = null;
}

/**
 * Process issues through AI-Fixer and return enriched results
 * Convenience function for pipeline integration
 *
 * @param issues Issues to process
 * @param options Processing options
 * @param options.parallel Number of parallel requests (default 3)
 * @param options.verbose Enable verbose logging
 * @param options.submitToRegistry Submit successful fixes to pattern registry
 */
export async function processIssuesWithAIFixer(
  issues: AIFixerIssue[],
  options?: {
    parallel?: number;
    verbose?: boolean;
    submitToRegistry?: boolean;
  }
): Promise<AIFixerBatchResult> {
  const agent = getAIFixerAgent({ submitToRegistry: options?.submitToRegistry });

  if (options?.submitToRegistry) {
    agent.enableRegistrySubmission();
  }

  const result = await agent.processBatch(issues, {
    parallel: options?.parallel,
    verbose: options?.verbose,
  });

  // Submit successful fixes to registry if enabled
  if (options?.submitToRegistry) {
    console.log('[AI-Fixer] Submitting successful fixes to pattern registry...');

    for (const enriched of result.enrichedIssues) {
      // Only submit high-confidence fixes
      if (enriched.fixRecommendation.confidence >= 70) {
        await agent.submitFixToRegistry(enriched, enriched.fixRecommendation);
      }
    }
  }

  return result;
}
