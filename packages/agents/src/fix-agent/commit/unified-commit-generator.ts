/**
 * Unified Commit Generator
 *
 * Generates commit messages and PR comments for all Git providers.
 * Supports GitHub, GitLab, Bitbucket, and Azure DevOps.
 *
 * Key features:
 * - Consistent commit message format across providers
 * - Respects provider-specific limits (title length, body format)
 * - Groups issues by category, severity, or file
 * - Generates educational content and references
 */

import {
  Provider,
  CommitStyle,
  CommitGroup,
  FixReportIssue,
  IssueCategory,
  IssueSeverity,
  FixCommit,
  CommitTemplate,
} from '../types/fix-report-types';

// ============================================================================
// Provider-Specific Templates
// ============================================================================

